export const languageLabel: Record<Language, string> = { uk: 'Українська', en: 'English' }

export function detectBrowserLanguage(): Language {
  if (typeof navigator === 'undefined') return 'en'
  return navigator.language.toLowerCase().startsWith('uk') ? 'uk' : navigator.language.toLowerCase().startsWith('en') ? 'en' : 'en'
}

